def make_docx(filename, title, version, dept, publish_date, effective_date, chapters):
    doc = Document()
    style = doc.styles['Normal']
    style.font.name = '宋体'
    style.font.size = Pt(12)

    tp = doc.add_paragraph()
    tp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = tp.add_run(title)
    r.bold = True
    r.font.size = Pt(18)
    r.font.name = '黑体'

    for line in [
        f"文件编号：{dept}-ZD-{random.randint(100, 999)}",
        f"版本号：{version}", f"制定部门：{dept}",
        f"发布日期：{publish_date}", f"生效日期：{effective_date}",
        "密级：内部公开",
    ]:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(line)
        r.font.size = Pt(10)
        r.font.color.rgb = RGBColor(100, 100, 100)

    doc.add_paragraph()
    doc.add_heading('修订记录', level=2)
    tbl = doc.add_table(rows=3, cols=4, style='Table Grid')
    for i, h in enumerate(['版本', '修订日期', '修订内容', '修订人']):
        c = tbl.rows[0].cells[i]; c.text = h
        for pp in c.paragraphs:
            for rr in pp.runs: rr.bold = True; rr.font.size = Pt(10)
    tbl.rows[1].cells[0].text = "V1.0"
    tbl.rows[1].cells[1].text = publish_date
    tbl.rows[1].cells[2].text = "初次发布"
    tbl.rows[1].cells[3].text = dept
    tbl.rows[2].cells[0].text = version
    tbl.rows[2].cells[1].text = effective_date
    tbl.rows[2].cells[2].text = "修订完善"
    tbl.rows[2].cells[3].text = dept
    doc.add_paragraph()

    for ch in chapters:
        doc.add_heading(ch['h'], level=1)
        for s in ch.get('s', []):
            if s.get('sh'):
                doc.add_heading(s['sh'], level=2)
            p = doc.add_paragraph()
            r = p.add_run(s['c'])
            r.font.size = Pt(12)
            p.paragraph_format.first_line_indent = Cm(0.74)
            p.paragraph_format.line_spacing = 1.5

    doc.add_paragraph(); doc.add_paragraph()
    st = doc.add_table(rows=3, cols=2)
    for i, (lbl, ph) in enumerate([("编制：","________________"),("审核：","________________"),("批准：","________________")]):
        st.rows[i].cells[0].text = lbl; st.rows[i].cells[1].text = ph

    fp = OUTPUT_DIR / f"{filename}.docx"
    doc.save(str(fp))
    print(f"  [OK] {fp.name}")


def make_txt(filename, title, version, dept, publish_date, effective_date, chapters):
    lines = [title, "=" * 60, ""]
    lines += [
        f"文件编号：{dept}-ZD-{random.randint(100, 999)}",
        f"版本号：{version}", f"制定部门：{dept}",
        f"发布日期：{publish_date}", f"生效日期：{effective_date}",
        "密级：内部公开", ""
    ]
    for ch in chapters:
        lines.append(f"# {ch['h']}")
        lines.append("")
        for s in ch.get('s', []):
            if s.get('sh'): lines.append(f"## {s['sh']}")
            lines.append(s['c']); lines.append("")
    lines.append("")
    lines.append("编制：________________    审核：________________    批准：________________")
    fp = OUTPUT_DIR / f"{filename}.txt"
    fp.write_text("\n".join(lines), encoding="utf-8")
    print(f"  [OK] {fp.name}")


