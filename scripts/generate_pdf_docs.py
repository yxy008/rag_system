"""
generate_pdf_docs.py - PDF 测试文档生成器
使用 reportlab 生成 100 篇内容不重复的中文 PDF 制度文档
"""
import os
import random
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import cm
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.lib.colors import HexColor
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

BASE_DIR = Path(__file__).parent.parent
OUTPUT_DIR = BASE_DIR / "documents"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# 注册中文字体
_fonts_registered = False


def register_fonts():
    global _fonts_registered
    if _fonts_registered:
        return
    font_dir = Path("C:/Windows/Fonts")
    font_map = {
        "SimHei": font_dir / "simhei.ttf",
        "SimSun": font_dir / "simsun.ttc",
        "SimKai": font_dir / "simkai.ttf",
        "SimFang": font_dir / "simfang.ttf",
    }
    for name, path in font_map.items():
        if path.exists():
            pdfmetrics.registerFont(TTFont(name, str(path)))
    _fonts_registered = True


register_fonts()

# 段落样式
styles = getSampleStyleSheet()
style_title = ParagraphStyle("ChTitle", fontName="SimHei", fontSize=22, leading=30, alignment=TA_CENTER, spaceAfter=20)
style_h1 = ParagraphStyle("ChH1", fontName="SimHei", fontSize=15, leading=22, spaceBefore=18, spaceAfter=10)
style_h2 = ParagraphStyle("ChH2", fontName="SimKai", fontSize=12, leading=18, spaceBefore=10, spaceAfter=6, leftIndent=0.5*cm)
style_body = ParagraphStyle("ChBody", fontName="SimSun", fontSize=11, leading=20, spaceBefore=2, spaceAfter=8, firstLineIndent=0.8*cm)
style_meta = ParagraphStyle("ChMeta", fontName="SimSun", fontSize=10, leading=16, alignment=TA_CENTER)


def make_pdf(filename, title, version, dept, publish_date, effective_date, chapters):
    fp = OUTPUT_DIR / f"{filename}.pdf"
    doc = SimpleDocTemplate(str(fp), pagesize=A4, topMargin=2*cm, bottomMargin=2*cm, leftMargin=2.5*cm, rightMargin=2.5*cm)
    story = []

    story.append(Spacer(1, 1*cm))
    story.append(Paragraph(title, style_title))
    story.append(Spacer(1, 0.5*cm))

    doc_id = f"{dept}-ZD-{random.randint(100, 999)}"
    meta_lines = [
        f"文件编号：{doc_id}　　版本号：{version}　　制定部门：{dept}",
        f"发布日期：{publish_date}　　生效日期：{effective_date}　　密级：内部公开",
    ]
    for ml in meta_lines:
        story.append(Paragraph(ml, style_meta))
    story.append(Spacer(1, 0.8*cm))

    story.append(Paragraph("修订记录", style_h1))
    rev_data = [
        ["版本", "修订日期", "修订内容", "修订人"],
        ["V1.0", publish_date, "初次发布", dept],
        [version, effective_date, "修订完善", dept],
    ]
    rev_table = Table(rev_data, colWidths=[3*cm, 4*cm, 6*cm, 3*cm])
    rev_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), "SimSun"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#999999")),
        ("BACKGROUND", (0, 0), (-1, 0), HexColor("#E8E8E8")),
        ("FONTNAME", (0, 0), (-1, 0), "SimHei"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(rev_table)
    story.append(Spacer(1, 0.8*cm))

    for ch_title, sections in chapters:
        story.append(Paragraph(ch_title, style_h1))
        for s in sections:
            if len(s) == 2:
                story.append(Paragraph(s[0], style_h2))
                story.append(Paragraph(s[1], style_body))
            else:
                story.append(Paragraph(s[0], style_body))

    story.append(Spacer(1, 1.5*cm))
    sign_data = [["编制：________________", "审核：________________", "批准：________________"]]
    sign_table = Table(sign_data, colWidths=[5*cm, 5*cm, 5*cm])
    sign_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), "SimSun"),
        ("FONTSIZE", (0, 0), (-1, -1), 11),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.append(sign_table)

    doc.build(story)
    print(f"  [OK] {fp.name}")


